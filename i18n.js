  function getLocale() { return locale; }
  function localePath(next, pathname = root.location?.pathname || '/') {
    const suffix = /(?:^|\/)sources(?:\.html)?\/?$/.test(pathname) ? '/sources' : '';
    return `/${next === LOCALES.zh ? 'zh' : 'en'}${suffix}`;
  }
  function updateMetadata() {
    if (!root.document) return;
    const doc = root.document;
    doc.documentElement.lang = locale === LOCALES.zh ? 'zh-CN' : 'en';
    doc.title = t('app.title');
    const description = doc.querySelector('meta[name="description"]');
    if (description) description.content = t('app.description');
    for (const selector of ['meta[property="og:title"]', 'meta[name="twitter:title"]']) {
      const node = doc.querySelector(selector);
      if (node) node.content = t('app.title');
    }
    for (const selector of ['meta[property="og:description"]', 'meta[name="twitter:description"]']) {
      const node = doc.querySelector(selector);
      if (node) node.content = t('app.description');
    }
    const ogUrl = doc.querySelector('meta[property="og:url"]');
    if (ogUrl) ogUrl.content = `https://www.btcaipro.com${localePath(locale)}`;
    const canonical = doc.querySelector('link[rel="canonical"]');
    if (canonical) canonical.href = `https://www.btcaipro.com${localePath(locale)}`;
    for (const link of doc.querySelectorAll('link[rel="alternate"][hreflang]')) {
      const hreflang = link.getAttribute('hreflang');
      const target = hreflang === 'zh-CN' ? LOCALES.zh : LOCALES.en;
      link.href = `https://www.btcaipro.com${hreflang === 'x-default' ? (localePath(locale).endsWith('/sources') ? '/sources' : '/') : localePath(target)}`;
    }
  }
  function setLocale(next, { persist = true, navigate = true, replace = false } = {}) {
    if (!Object.values(LOCALES).includes(next)) return false;
    locale = next;
    if (persist) try { root.localStorage?.setItem(STORAGE_KEY, next); } catch (_) { /* storage may be blocked */ }
    if (navigate && root.history && root.location) root.history[replace ? 'replaceState' : 'pushState'](null, '', localePath(next, root.location.pathname));
    updateMetadata();
    listeners.forEach(listener => listener(next));
    return true;
  }
  function onChange(listener) { listeners.add(listener); return () => listeners.delete(listener); }
  function hasTranslation(key) { return Object.hasOwn(dictionaries[locale], key); }
  function t(key, params = {}, readableFallback = '') {
    const phrase = dictionaries[locale][key] ?? dictionaries['zh-CN'][key] ?? readableFallback ?? '';
    if (!Object.hasOwn(dictionaries[locale], key) && ((typeof process !== 'undefined' && process.env?.NODE_ENV === 'development') || root.location?.hostname === 'localhost' || root.location?.hostname === '127.0.0.1')) {
      root.console?.warn?.(`Missing translation: ${key}`);
    }
    if (phrase) return phrase.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
    return key.split('.').pop().replace(/([A-Z])/g, ' $1').replace(/[_-]/g, ' ').trim();
  }
  function formatNumber(value, options = {}) { return new Intl.NumberFormat(locale, options).format(value); }
  function formatCompactNumber(value, digits = 2) {
    const number = Number(value);
    if (!Number.isFinite(number)) return '--';
    const abs = Math.abs(number);
    const units = locale === LOCALES.zh
      ? [[1e12, '万亿'], [1e8, '亿'], [1e4, '万']]
      : [[1e12, 'T'], [1e9, 'B'], [1e6, 'M'], [1e3, 'K']];
    const unit = units.find(([scale]) => abs >= scale);
    if (!unit) return formatNumber(number, { maximumFractionDigits: digits });
    return `${formatNumber(number / unit[0], { maximumFractionDigits: digits })}${unit[1]}`;
  }
  function formatCurrency(value, { compact = false, minimumFractionDigits = 2, maximumFractionDigits = 2 } = {}) {
    const prefix = locale === LOCALES.zh ? '$ ' : '$';
    if (compact) return `${prefix}${formatCompactNumber(value, maximumFractionDigits)}`;
    return `${prefix}${formatNumber(value, { minimumFractionDigits, maximumFractionDigits })}`;
  }
  function formatPercent(value, digits = 2) {
    const number = Number(value);
    return `${number >= 0 ? '+' : ''}${formatNumber(number, { minimumFractionDigits: digits, maximumFractionDigits: digits })}%`;
  }
  function validDate(value) { const date = new Date(value); return Number.isFinite(date.getTime()) ? date : null; }
  function formatDate(value, options = {}) { const date = validDate(value); return date ? new Intl.DateTimeFormat(locale, { year: 'numeric', month: 'numeric', day: 'numeric', ...options }).format(date) : ''; }
  function formatTime(value, options = {}) { const date = validDate(value); return date ? new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false, ...options }).format(date) : ''; }
  function formatDateTime(value, options = {}) { const date = validDate(value); return date ? `${formatDate(date, options)} ${formatTime(date, options)}` : ''; }
  function initRoute() {
    if (!root.location || !root.history) return;
    if (!routeLocale(root.location.pathname)) setLocale(locale, { persist: false, replace: true });
    else updateMetadata();
    root.addEventListener?.('popstate', () => {
      const next = routeLocale(root.location.pathname) || resolveInitialLocale();
      setLocale(next, { navigate: false, persist: false });
    });
  }
  return { STORAGE_KEY, LOCALES, dictionaries, getLocale, setLocale, onChange, routeLocale, localePath,
    savedLocale, browserLocale, resolveInitialLocale, hasTranslation, t, formatNumber, formatCompactNumber,
    formatCurrency, formatPercent, formatDate, formatTime, formatDateTime, initRoute };
