  function routeLocale(pathname = '/') {
    const segment = pathname.split('/')[1];
    return LOCALES[segment] || null;
  }
  function savedLocale(storage = root.localStorage) {
    try {
      const value = storage?.getItem(STORAGE_KEY);
      return Object.values(LOCALES).includes(value) ? value : null;
    } catch (_) { return null; }
  }
  function browserLocale(navigatorObject = root.navigator) {
    const choices = [navigatorObject?.language, ...(navigatorObject?.languages || [])];
    return choices.some(value => /^zh(?:-|$)/i.test(String(value || ''))) ? LOCALES.zh : LOCALES.en;
  }
  function resolveInitialLocale({ pathname = root.location?.pathname || '/', storage = root.localStorage, navigatorObject = root.navigator } = {}) {
    return routeLocale(pathname) || savedLocale(storage) || browserLocale(navigatorObject);
  }
  let locale = resolveInitialLocale();
